/*
 * Written-domain matrices (the lead's rulings on the merged S6's B1 and B2; A4, F17b, the design's fit rule; ADR 0021 1.3;
 * V30 §13): a written type, or a copy of one, admits exactly what the type permits at every level, whatever is stored.
 * Each case is generated by axes from a V30 §13 form; every expectation is the form's own: the admitted kinds per level,
 * the checked type of each store that brings a host value, and which host values fit.
 */

type Decision =
  | "written"
  | "early copy"
  | "later copy"
  | "copy of a copy"
  | "copy of a copy of a copy"
  | "projection"
  | "copy of a projection"
  | "copy of an empty intermediate"
  | "later copy of an empty intermediate"
  | "copy of a null intermediate"
  | "copy of a null-element intermediate"
  | "copy of an otherwise"
  | "copy of a get default";

type Host = "direct" | "named" | "index-held";

const HOSTS: readonly Host[] = ["direct", "named", "index-held"];
const DIRECT: readonly Host[] = ["direct"];

/**
 * Whether `WRITTEN_DOMAIN_MATRIX` and `V30_TYPE_MATRIX` are their whole products, else the factored samples the tests
 * run (each matrix says what it keeps). The whole products are a laptop run outside CI: `WRITTEN_MATRICES_FULL=1 node
 * tools/test-output-filter.mjs dist/tests/type-core/written/type-core-written-matrices.test.js
 * dist/tests/type-core/sharing/type-core-sharing-differential.test.js`.
 */
const FULL = process.env["WRITTEN_MATRICES_FULL"] === "1";

/** One source: its place, the form it holds, what each level admits, the checked stores and which values fit. */
export interface WrittenCase {
  readonly name: string;
  readonly source: string;
  /** The binding under test: the written one, or the copy. */
  readonly place: string;
  readonly form: string;
  /** How the place under test is decided (`Decision`), for the test's account of what the route takes. */
  readonly decision: string;
  readonly levels: readonly (readonly string[])[];
  /** The plan's checked stores, all of them in order, `start:end type`, where the candidate route takes the source. */
  readonly checks: readonly string[];
  /** Per host value, `null` where it fits, else where it stops (`TSR058@start:end`). */
  readonly runs: readonly (readonly [SerializableRuntimeValue, string | null])[];
  /**
   * The other host values every run gives: a written binding with no literal of its form starts as `hostInit`, a value
   * of its form (else one no host value can be, which stops every run there).
   */
  readonly globals: Readonly<Record<string, SerializableRuntimeValue>>;
  /**
   * Whether the candidate route takes the source by its own axes (Astra's D1): no set or dict element type, no written
   * union (S10) and no function (S7's slice takes `otherwise` and `get`); else the decision layer alone.
   */
  readonly executable: boolean;
  /**
   * The lines whose store brings a host value to a level of its destination that is decided (not every kind), or carries
   * a host-started binding's external data on (`CARRIED`): each has the runtime-check warning there (`written-target`,
   * `warning-runtime-check`), and no other diagnostic is reported.
   */
  readonly warned: readonly string[];
  /**
   * The program's C9 boundaries, sorted, each `root level [kinds] start:end`: one per store that brings the host value,
   * at the host read, against what its destination admits at the level it lands at; none where that level admits every
   * kind; a named host value's at its own unwritten binding, which nothing decides (`[unknown]`).
   */
  readonly boundaries: readonly string[];
}

/** The level `valueOf`'s leaf stands at: its collections' nesting along the first members. */
function leafDepth(form: Form): number {
  switch (form.kind) {
    case "name":
      return 0;
    case "optional":
      return leafDepth(form.of);
    case "union":
      return leafDepth(form.members[0]!);
    case "collection":
      return 1 + leafDepth(form.of);
  }
}

/** The C9 boundary a host read at `site` owes where it lands in `root` at `level` of `levels`, if any (`boundaries`). */
function boundaryAt(
  root: string,
  levels: readonly (readonly string[])[],
  level: number,
  site: string,
): string[] {
  const kinds = levels[level]!;
  return kinds.includes("unknown")
    ? []
    : [`${root} ${level} [${[...kinds].sort().join(",")}] ${site}`];
}

/** The site of `of` in `line` of `source`, as `start:end`. */
function siteIn(source: string, line: string, of: string): string {
  const start = source.indexOf(`${line}\n`) + line.indexOf(of);
  return `${start}:${start + of.length}`;
}

/**
 * The source of `form` under `decision` with the host value `host`: `typed` written with the form, initialised with a
 * literal of it (else the host value), then the place that receives the host value (`typed` itself, a copy taken
 * before or after that store, a copy at the end of a chain of two or three copies, or, with `projection`, a copy of the
 * written list's element, with `copy of a projection` a copy of that copy; or a copy of a place whose written type comes
 * later than its start, `[]` for a list and `null` otherwise, through a selected `otherwise`, or as an empty list's
 * `get` default: the seeds of Sol's round 2).
 */
function writtenCase(form: Form, decision: Decision, host: Host): WrittenCase {
  const type = formText(form);
  const literal = leafLiteral(form);
  const init = valueOf(form, literal ?? "hostInit");
  // (a host-started binding's own value: one of its form where a host value can be, so the copies after it run)
  const fittingAt = FITTING_POOL.findIndex((given) => fits(leafForm(form), given));
  const initial =
    literal === null
      ? fittingAt >= 0
        ? FITTING_POOL[fittingAt]!
        : HOST_VALUES.find((given) => !fits(leafForm(form), given))!
      : null;
  const projected = decision === "projection" || decision === "copy of a projection";
  const placed = projected && form.kind === "collection" ? form.of : seeded(form, decision);
  const leaf = host === "direct" ? "hostValue" : host === "named" ? "h" : "[hostValue][0]";
  // (a later copy's host store holds the host value whole: a literal around it would decide its levels first, A2; an
  // empty intermediate's copies take it whole too, Astra's F1)
  const whole =
    decision === "later copy" ||
    decision === "copy of an empty intermediate" ||
    decision === "later copy of an empty intermediate";
  const value = whole ? leaf : valueOf(placed, leaf);
  const lines = [
    ...(host === "named" ? ["let h = hostValue"] : []),
    `let typed: ${type} = ${init}`,
  ];
  let hostLine: string;
  switch (decision) {
    case "written":
      hostLine = `typed = ${value}`;
      lines.push(hostLine);
      break;
    case "early copy":
      hostLine = `copy = ${value}`;
      lines.push("let copy = typed", hostLine);
      break;
    case "later copy":
      hostLine = `let copy = ${value}`;
      lines.push(hostLine, "copy = typed");
      break;
    case "copy of a copy":
      hostLine = `copy = ${value}`;
      lines.push("let middle = typed", "let copy = middle", hostLine);
      break;
    case "copy of a copy of a copy":
      hostLine = `copy = ${value}`;
      lines.push("let first = typed", "let second = first", "let copy = second", hostLine);
      break;
    case "projection":
      hostLine = `copy = ${value}`;
      lines.push("let copy = typed[0]", hostLine);
      break;
    case "copy of a projection":
      hostLine = `copy = ${value}`;
      lines.push("let middle = typed[0]", "let copy = middle", hostLine);
      break;
    case "copy of an empty intermediate":
      hostLine = `copy = ${value}`;
      lines.push("let middle = []", "middle = typed", "let copy = middle", hostLine);
      break;
    case "later copy of an empty intermediate":
      hostLine = `let copy = ${value}`;
      lines.push("let middle = []", "middle = typed", hostLine, "copy = middle");
      break;
    case "copy of a null intermediate":
      hostLine = `copy = ${value}`;
      lines.push("let middle = null", "middle = typed", "let copy = middle", hostLine);
      break;
    case "copy of a null-element intermediate":
      hostLine = `copy = ${value}`;
      lines.push("let middle = [null]", "middle = typed", "let copy = middle", hostLine);
      break;
    case "copy of an otherwise":
      hostLine = `copy = ${value}`;
      lines.push("let middle = null otherwise typed", "let copy = middle", hostLine);
      break;
    case "copy of a get default":
      hostLine = `copy = ${value}`;
      lines.push("let middle = [].get(0, default: typed)", "let copy = middle", hostLine);
      break;
  }
  const source = `${[...lines, 'say "DONE"', "exit"].join("\n")}\n`;
  const span = (line: string, of: string): { store: string; value: string } => {
    const start = source.indexOf(`${line}\n`);
    const end = start + line.length;
    return { store: `${start}:${end}`, value: `${end - of.length}:${end}` };
  };
  // the stores that check a host value, in order: the initial value at the leaf where there is no literal, then the
  // host store's, at the leaf or whole
  const stores = [
    ...(literal === null
      ? [
          {
            ...span(`let typed: ${type} = ${init}`, init),
            whole: false,
            of: form,
            line: `let typed: ${type} = ${init}`,
          },
        ]
      : []),
    { ...span(hostLine, value), whole, of: placed, line: hostLine },
  ];
  const stopOf = (given: SerializableRuntimeValue): string | null => {
    const stop = stores.find(
      (store, index) =>
        !fits(
          store.whole ? store.of : leafForm(store.of),
          index === 0 && literal === null ? initial! : given,
        ),
    );
    return stop === undefined ? null : `TSR058@${stop.value}`;
  };
  const tried = [...HOST_VALUES];
  if (tried.every((given) => stopOf(given) !== null)) {
    const fitting = FITTING_POOL.find((given) => stopOf(given) === null);
    if (fitting !== undefined) tried.push(fitting);
  }
  const runs = tried.map((given): readonly [SerializableRuntimeValue, string | null] => [
    given,
    stopOf(given),
  ]);
  const place = decision === "written" ? "typed" : "copy";
  const boundaries = [
    ...(literal === null
      ? boundaryAt(
          "typed",
          levelsOf(form),
          leafDepth(form),
          siteIn(source, `let typed: ${type} = ${init}`, "hostInit"),
        )
      : []),
    ...(host === "named"
      ? [`h 0 [unknown] ${siteIn(source, "let h = hostValue", "hostValue")}`]
      : boundaryAt(
          place,
          levelsOf(placed),
          whole ? 0 : leafDepth(placed),
          siteIn(source, hostLine, "hostValue"),
        )),
  ];
  // (a store warns where its host value lands at a decided level: whole at the place's own, else at its leaf's)
  const carried = (literal === null ? CARRIED[decision] : [])
    .filter(([, depth]) => leafDepth(form) > depth)
    .map(([line]) => ({ ...span(line, ""), of: placed, line }));
  const checked = [...stores, ...carried].sort(
    (a, b) => source.indexOf(`${a.line}\n`) - source.indexOf(`${b.line}\n`),
  );
  const warned = [
    ...stores.flatMap(({ of, whole: atRoot, line }) =>
      levelsOf(of)[atRoot ? 0 : leafDepth(of)]!.includes("unknown") ? [] : [line],
    ),
    ...carried.map(({ line }) => line),
  ];
  return {
    name: `${type}, ${decision}, ${host}`,
    source,
    place,
    form: formText(placed),
    decision,
    levels: levelsOf(placed),
    checks: checked.map(({ store, of }) => `${store} ${checkedText(of)}`),
    runs,
    globals: literal === null ? { hostInit: initial! } : {},
    executable: inSlice(form),
    warned,
    boundaries: boundaries.sort(),
  };
}

/**
 * The copies each decision makes of `typed` and of the places between it and the copy, in source order, each with the
 * steps it projects below `typed`'s root (`typed[0]`: one). Where `typed` starts as a host value (`hostInit`) below the
 * root of what a copy takes (`let typed: T[] = [hostInit]` copied whole, `T[][]` through `typed[0]`), the copy carries
 * that external data on and owes its runtime check where it lands, against its destination's whole type (C9);
 * a host value at that root is checked whole where it is stored, and an `otherwise` or a `get` gives its own result.
 */
const CARRIED: Readonly<Record<Decision, readonly (readonly [string, number])[]>> = {
  written: [],
  "early copy": [["let copy = typed", 0]],
  "later copy": [["copy = typed", 0]],
  "copy of a copy": [
    ["let middle = typed", 0],
    ["let copy = middle", 0],
  ],
  "copy of a copy of a copy": [
    ["let first = typed", 0],
    ["let second = first", 0],
    ["let copy = second", 0],
  ],
  projection: [["let copy = typed[0]", 1]],
  "copy of a projection": [
    ["let middle = typed[0]", 1],
    ["let copy = middle", 1],
  ],
  "copy of an empty intermediate": [
    ["middle = typed", 0],
    ["let copy = middle", 0],
  ],
  "later copy of an empty intermediate": [
    ["middle = typed", 0],
    ["copy = middle", 0],
  ],
  "copy of a null intermediate": [
    ["middle = typed", 0],
    ["let copy = middle", 0],
  ],
  "copy of a null-element intermediate": [
    ["middle = typed", 0],
    ["let copy = middle", 0],
  ],
  "copy of an otherwise": [],
  "copy of a get default": [],
};

/**
 * The form a seeded intermediate's copy holds (Astra's F2: the inherited decision keeps the intermediate's own `null`):
 * after a `null` start the form made optional, after a `[null]` start its element made optional; else the form.
 */
function seeded(form: Form, decision: Decision): Form {
  if (decision === "copy of a null intermediate")
    return levelsOf(form)[0]!.includes("null") ? form : optional(form);
  if (decision === "copy of a null-element intermediate" && form.kind === "collection")
    return levelsOf(form)[1]!.includes("null")
      ? form
      : collection(form.collection, optional(form.of));
  return form;
}

/**
 * The decisions the matrices take: the written place, an early or a later copy, and a copy at the end of a chain of two
 * or three whole copies (A4 reaches through them: the lead's ruling on chains).
 */
const DECISIONS: readonly Decision[] = [
  "written",
  "early copy",
  "later copy",
  "copy of a copy",
  "copy of a copy of a copy",
];

/** The decisions of a written list's element: a copy of it (a typed index projection), and a copy of that copy. */
const PROJECTIONS: readonly Decision[] = ["projection", "copy of a projection"];

/**
 * Where a copied place's own written type comes from besides a whole copy at its start (Sol's round 2: the seeds; Astra's
 * F1, F2): a later store after an empty list (its copy taken before or after the host value) or after `null`, a list of
 * `null` before it, a selected `otherwise`, an empty list's `get` default; its copy keeps the place's decision,
 * the place's own `null` included.
 */
const SEEDS: readonly Decision[] = [
  "copy of an empty intermediate",
  "later copy of an empty intermediate",
  "copy of a null intermediate",
  "copy of a null-element intermediate",
  "copy of an otherwise",
  "copy of a get default",
];

/** The seeds that start the intermediate as a list: the forms that are a list, not optional. */
const LIST_SEEDS: readonly Decision[] = [
  "copy of an empty intermediate",
  "later copy of an empty intermediate",
  "copy of a null-element intermediate",
];

/** The seeds that apply to a form. */
const seedsOf = (form: Form): readonly Decision[] =>
  form.kind === "collection" && form.collection === "list"
    ? SEEDS
    : SEEDS.filter((seed) => !LIST_SEEDS.includes(seed));

/**
 * The forms whose rows also take the host value named or held at an index: where a host read lands is the decision's,
 * not the transport's, so these cross it with a whole number, its optional and `null` alone, with lists one and two
 * deep, their element or the outer list optional and a list of `null`, and with three lists, both the element and the
 * outer list optional.
 */
const HOST_FORMS: ReadonlySet<string> = new Set([
  "integer",
  "integer?",
  "null",
  "integer[]",
  "integer?[]",
  "integer[][]",
  "integer[]?",
  "null[]",
  "integer?[][][]?",
]);

/**
 * The merged S6's B1 (the reviewer's written-domain matrix, rebuilt by axes): nine element domains (the four usual
 * scalars, each optional, and `null` alone) × list depths 0–3, the outermost list optional or not × the place written,
 * an early or a later copy, a copy at the end of a chain of two or three copies, a copy of the written list's element
 * (a typed index projection) or a copy of that copy, a copy of a place typed by each seed (`SEEDS`) × the host value
 * direct, and for `HOST_FORMS` (every form with `FULL`) named or held at an index too; and a swap of a `null`
 * intermediate (`nullSwap`) and a copy of a literal with `null` beside its written copy (`literalNull`).
 */
export const WRITTEN_DOMAIN_MATRIX: readonly WrittenCase[] = (() => {
  const out: WrittenCase[] = [];
  const domains = ["integer", "number", "string", "boolean"].flatMap((kind) => [
    name(kind),
    optional(name(kind)),
  ]);
  domains.push(name("null"));
  for (const domain of domains)
    for (const depth of [0, 1, 2, 3])
      for (const outerOptional of depth === 0 ? [false] : [false, true]) {
        let form = domain;
        for (let level = 0; level < depth; level += 1) form = collection("list", form);
        if (outerOptional) form = optional(form);
        for (const decision of [...DECISIONS, ...PROJECTIONS, ...seedsOf(form)]) {
          if (PROJECTIONS.includes(decision) && (outerOptional || depth === 0)) continue;
          for (const host of FULL || HOST_FORMS.has(formText(form)) ? HOSTS : DIRECT)
            out.push(writtenCase(form, decision, host));
        }
      }
  out.push(nullSwap(), literalNull());
  return out;
})();

/**
 * Sol's round 3 B1: a literal's `null` beside a written copy makes its element optional (A8, ADR 0021 1.3), so a copy of
 * the literal's place keeps it; the host value then stored into the copy's element.
 */
function literalNull(): WrittenCase {
  const hostLine = "out = [hostValue]";
  const lines = [
    "let typed: integer = 1",
    "let middle = [null, typed]",
    "let out = middle",
    hostLine,
  ];
  const source = `${[...lines, 'say "DONE"', "exit"].join("\n")}\n`;
  const start = source.indexOf(`${hostLine}\n`);
  const site = siteIn(source, hostLine, "hostValue");
  const stored = siteIn(source, hostLine, "[hostValue]");
  const form = collection("list", optional(name("integer")));
  return {
    name: "integer, a copy of a literal with null beside the copy, direct",
    source,
    place: "out",
    form: formText(form),
    decision: "a copy of a literal with null beside the copy",
    levels: levelsOf(form),
    checks: [`${start}:${start + hostLine.length} list<integer|null>`],
    runs: HOST_VALUES.map((given) => [
      given,
      fits(leafForm(form), given) ? null : `TSR058@${stored}`,
    ]),
    globals: {},
    executable: true,
    warned: [hostLine],
    boundaries: [`out 1 [integer,null] ${site}`],
  };
}

/**
 * Astra's F2 in a swap: `a` is optional by its own `null` before its written copy, so `tmp`, its copy, is too, past the
 * swap's copies back (`a = b`, `b = tmp`); the host value then stored into `tmp`.
 */
function nullSwap(): WrittenCase {
  const hostLine = "tmp = hostValue";
  const lines = [
    "let typed: integer = 1",
    "let a = null",
    "a = typed",
    "let b = 2",
    "let tmp = a",
    "a = b",
    "b = tmp",
    hostLine,
  ];
  const source = `${[...lines, 'say "DONE"', "exit"].join("\n")}\n`;
  const start = source.indexOf(`${hostLine}\n`);
  const site = siteIn(source, hostLine, "hostValue");
  const form = optional(name("integer"));
  return {
    name: "integer, a swap of a null intermediate, direct",
    source,
    place: "tmp",
    form: formText(form),
    decision: "a swap of a null intermediate",
    levels: levelsOf(form),
    checks: [`${start}:${start + hostLine.length} integer|null`],
    runs: HOST_VALUES.map((given) => [given, fits(form, given) ? null : `TSR058@${site}`]),
    globals: {},
    executable: true,
    warned: [hostLine],
    boundaries: [`tmp 0 [integer,null] ${site}`],
  };
}

/** The decisions a composition takes (`compositionsOf`). */
const COMPOSED: readonly Decision[] = ["written", "early copy", "later copy"];

/** The decision of a name outside `CROSSED_NAMES`: the place written. */
const WRITTEN: readonly Decision[] = ["written"];

/**
 * Representative compositions of a type name `t` beyond `V30_TYPE_MATRIX`'s forms (Astra's M1), exactly these:
 * - unions `(T | U) set`, `(T | U) dict` (V30 §13's valid examples b, c), `(T | U)[][]`, `(T | U)[][][]`, `(T | U)?`,
 *   `T? | U`, `(T? | U)[]` and `T | U | V`;
 * - `T? set`, `T? dict`, `T set?`, `T dict?`, `T? set?`, `T? dict?`;
 * - `T[]? set`, `T[]? dict`, `T?[] set`, `T?[] dict`;
 * - `T set[]`, `T dict[]`, `T set set`, `T dict dict`, `T dict set`, `T set dict`;
 * - `T[][] set`, `T[][] dict`;
 * - and every placement of `?` in lists nested two and three deep.
 * Left out: the other placements of `?` in mixed forms, even two deep (`T set?[]`, `T? set[]`, `T[] set?`, `T set? set`
 * and their dict forms); the other placements of `?` around unions (`(T | U)?[]`, `(T | U)[]?`, `(T | U) set?`); other
 * member combinations, four or more names, and unions nested further (`((T | U) set)[]`); the other three-level mixed
 * sequences (`T set[][]`, `T[] set[]`, `T dict[] set`, …). A union holding a whole collection beside another type is
 * V30 §13's error (`UNION_RULE_MATRIX`) and has none: `list`, `set` and `dict` take no union; `null?` is `null`, so `null`
 * takes no optional leaf.
 */
function compositionsOf(t: Form, u: Form, base: string): Form[] {
  const opt = (of: Form): Form => (base === "null" ? of : optional(of));
  const third = name(base === "boolean" ? "integer" : "boolean");
  const collected = base !== "object" && UNRESTRICTED.has(base);
  const unions = collected
    ? []
    : [
        collection("set", union(t, u)),
        collection("dict", union(t, u)),
        collection("list", collection("list", union(t, u))),
        collection("list", collection("list", collection("list", union(t, u)))),
        optional(union(t, u)),
        ...(base === "null"
          ? []
          : [union(optional(t), u), collection("list", union(optional(t), u))]),
        union(t, u, third),
      ];
  const optionals: Form[] = [];
  for (const depth of [2, 3])
    for (let mask = 0; mask < 1 << (depth + 1); mask += 1) {
      if (base === "null" && mask & 1) continue;
      let form = mask & 1 ? optional(t) : t;
      for (let level = 1; level <= depth; level += 1) {
        form = collection("list", form);
        if (mask & (1 << level)) form = optional(form);
      }
      optionals.push(form);
    }
  return [
    ...unions,
    collection("set", opt(t)),
    collection("dict", opt(t)),
    optional(collection("set", t)),
    optional(collection("dict", t)),
    optional(collection("set", opt(t))),
    optional(collection("dict", opt(t))),
    collection("set", optional(collection("list", t))),
    collection("dict", optional(collection("list", t))),
    collection("set", collection("list", opt(t))),
    collection("dict", collection("list", opt(t))),
    collection("list", collection("set", t)),
    collection("list", collection("dict", t)),
    collection("set", collection("set", t)),
    collection("dict", collection("dict", t)),
    collection("set", collection("dict", t)),
    collection("dict", collection("set", t)),
    collection("set", collection("list", collection("list", t))),
    collection("dict", collection("list", collection("list", t))),
    ...optionals,
  ];
}

/**
 * The names whose forms `V30_TYPE_MATRIX` also copies, projects, seeds and feeds named or held at an index: one per way
 * the core moves and checks a copied kind. A copy, a projection or a seed moves what a written type admits as a set of
 * kinds and rebuilds a copy's checked type by the kind's class (`closedType`: a scalar, `null`, a collection, `object`,
 * a plain kind); a binding whose form has no literal starts as host data its copies carry on (`CARRIED`), by where the
 * data comes from, whatever its kind. So: the whole number and the number (scalars, the one pair where a kind fits
 * another), `null` alone, the unrestricted collections and `object`, and `range` (a plain kind a host value can be);
 * `object`, `set`, `dict` and `range` start as host data. Every other name's own kind, its check and its values are its
 * forms', written and fed directly. A copy rule that comes to depend on a kind needs that kind's class crossed here:
 * `FULL` shows what the sample would miss.
 */
const CROSSED_NAMES: ReadonlySet<string> = new Set([
  "integer",
  "number",
  "null",
  "list",
  "set",
  "dict",
  "object",
  "range",
]);

/**
 * V30 §13's written-type matrix (the orchestrator's instruction): every type name (the scalars, `null`, the
 * unrestricted `list`, `set`, `dict`, `object`, the program-control names) in each form V30 §13 lists, `T`, `T?`, `T[]`,
 * `T set`, `T dict`, `T?[]`, `T[]?`, `T | U` and `(T | U)[]` (beside `string`, `integer` for a `string`), nested to depth
 * three (`T[][]`, `T?[][]`, `T[]?[]`, `T[] set`, `T[] dict`, `T[][][]`), × the place written, an early or a later copy, a
 * copy at the end of a chain of two or three copies, for a list form a copy of its element (a typed index projection)
 * or a copy of that copy × the host value direct, named or held at an index; for a form of depth one at most a copy of
 * a place typed by each seed (`SEEDS`), the host value direct; and representative compositions of the name
 * through the same depth (`compositionsOf`), written, an early and a later copy, the host value direct. The copies,
 * projections, seeds and the host value named or held at an index are `CROSSED_NAMES`' (every name's with `FULL`); the
 * other names' forms and compositions are written with the host value direct. `null?` is `null`, so the forms that
 * only make `null` optional are left out, while its optional collection layers (`null[]?`, `null[]?[]`) remain. A
 * union holding a whole collection beside another type is V30 §13's compile error and has no form here:
 * `UNION_RULE_MATRIX` holds those.
 */
export const V30_TYPE_MATRIX: readonly WrittenCase[] = (() => {
  const out: WrittenCase[] = [];
  for (const base of [...SCALAR_NAMES, "null", ...UNRESTRICTED_NAMES, ...CONTROL_NAMES]) {
    const t = name(base);
    const other = name(base === "string" ? "integer" : "string");
    const collected = base !== "object" && UNRESTRICTED.has(base);
    // (`null?` is `null`: the forms that only make `null` optional are its plain ones; an optional collection stays)
    const opt = (of: Form): Form => (base === "null" ? of : optional(of));
    const forms: Form[] = [
      t,
      ...(base === "null" ? [] : [optional(t)]),
      collection("list", t),
      collection("set", t),
      collection("dict", t),
      ...(base === "null" ? [] : [collection("list", opt(t))]),
      optional(collection("list", t)),
      collection("list", collection("list", t)),
      ...(base === "null" ? [] : [collection("list", collection("list", opt(t)))]),
      collection("list", optional(collection("list", t))),
      collection("set", collection("list", t)),
      collection("dict", collection("list", t)),
      collection("list", collection("list", collection("list", t))),
      // a union never holds a whole collection beside another type (V30 §13): unions of the others only
      ...(collected ? [] : [union(t, other), collection("list", union(t, other))]),
    ];
    // representative compositions of them through the same depth (Astra's M1, `compositionsOf`), each written, an early and a
    // later copy, the host value direct
    // (each written text once: `null set?` is both an optional set of `null` and one of `null?`)
    const known = new Set(forms.map(formText));
    const crossed = FULL || CROSSED_NAMES.has(base);
    for (const form of compositionsOf(t, other, base)) {
      if (known.has(formText(form))) continue;
      known.add(formText(form));
      for (const decision of crossed ? COMPOSED : WRITTEN)
        out.push(writtenCase(form, decision, "direct"));
    }
    for (const form of forms) {
      if (depthOf(form) > 3) continue;
      const list = form.kind === "collection" && form.collection === "list";
      for (const decision of crossed ? [...DECISIONS, ...(list ? PROJECTIONS : [])] : WRITTEN)
        for (const host of crossed ? HOSTS : DIRECT) out.push(writtenCase(form, decision, host));
      // (the seeds with the host value direct: every placement of it is the written-domain matrix's)
      if (crossed && depthOf(form) <= 1)
        for (const decision of seedsOf(form)) out.push(writtenCase(form, decision, "direct"));
    }
  }
  return out;
})();

/**
 * The reviewer's Q1, ruled (ADR 0021 §1.2: an unannotated `integer` "is a `number` when any of them can store a non-whole
 * number, wherever that assignment is"; ADR 0021 §1.1: "the decided type holds wherever the place is used, also before the value
 * that decided it"): a copy of an unannotated source has the source's whole-source type, so a fraction or a
 * `null` stored into the source after the copy was taken widens the copy too, as it would before it. A2's value at the
 * store's node only selects the decider. Axes: a fraction or a `null` × list depths 0–2 × the copy taken before or after
 * that store × the host value direct, named or held at an index; the host value then stored into the copy.
 */
export const INFERRED_COPY_MATRIX: readonly WrittenCase[] = (() => {
  const out: WrittenCase[] = [];
  const wrap = (inner: string, depth: number): string =>
    "[".repeat(depth) + inner + "]".repeat(depth);
  for (const [widening, leafKinds] of [
    ["2.5", ["number"]],
    ["null", ["integer", "null"]],
  ] as const)
    for (const depth of [0, 1, 2])
      for (const copied of ["before", "after"] as const)
        for (const host of HOSTS) {
          const leaf = host === "direct" ? "hostValue" : host === "named" ? "h" : "[hostValue][0]";
          const value = wrap(leaf, depth);
          const hostLine = `copy = ${value}`;
          const lines = [
            ...(host === "named" ? ["let h = hostValue"] : []),
            `let original = ${wrap("1", depth)}`,
            ...(copied === "before" ? ["let copy = original"] : []),
            `original = ${wrap(widening, depth)}`,
            ...(copied === "after" ? ["let copy = original"] : []),
            hostLine,
          ];
          const source = `${[...lines, 'say "DONE"', "exit"].join("\n")}\n`;
          const start = source.indexOf(`${hostLine}\n`);
          const end = start + hostLine.length;
          const kinds: string[] = [...leafKinds].sort();
          const levels = [...Array.from({ length: depth }, () => ["list"]), kinds];
          out.push({
            name: `copy ${copied} ${widening} into the source, depth ${depth}, ${host}`,
            source,
            place: "copy",
            form: wrap(kinds.join("|"), 0),
            decision: `copy ${copied} the store`,
            levels,
            checks: [
              `${start}:${end} ${"list<".repeat(depth)}${kinds.join("|")}${">".repeat(depth)}`,
            ],
            runs: HOST_VALUES.map((given) => [
              given,
              kindsOf(given).some((kind) => kinds.includes(kind))
                ? null
                : `TSR058@${end - value.length}:${end}`,
            ]),
            globals: {},
            executable: true,
            // (a copy taken after the `null`: its own store holds `null`, which decides nothing, and the host value
            // nothing either, so its contract's kinds are published: a host value brought inline owes its boundary
            // only, a named one, which another store brought, its check at the store too)
            warned: widening === "null" && copied === "after" && host !== "named" ? [] : [hostLine],
            boundaries:
              host === "named"
                ? [`h 0 [unknown] ${siteIn(source, "let h = hostValue", "hostValue")}`]
                : boundaryAt("copy", levels, depth, siteIn(source, hostLine, "hostValue")),
          });
        }
  return out;
})();

/**
 * A chain through an unannotated parameter's default (F21, ADR 0021 1.5: the default is the parameter's start value,
 * checked once at the function against the body, and an argument beside it decides nothing): `p = typed`
 * makes `p` a copy of the written binding, so `let out = p` in the body has its type, with a call before or after the
 * function, or two calls, each passing another kind. A function is outside the candidate slice: the decision layer only.
 */
export const DEFAULT_CHAIN_MATRIX: readonly WrittenCase[] = (() => {
  const out: WrittenCase[] = [];
  for (const form of [name("null"), optional(name("integer")), collection("list", name("string"))])
    for (const calls of ["a call before", "a call after", "two calls"] as const) {
      const type = formText(form);
      const call = `use(${leafKinds(form).includes("string") ? "true" : '"other"'})`;
      const lines = [
        `let typed: ${type} = ${valueOf(form, leafLiteral(form)!)}`,
        ...(calls === "a call before" ? [call] : []),
        "function use(p = typed) {",
        " let out = p",
        " out = hostValue",
        "}",
        ...(calls === "a call after" ? [call] : calls === "two calls" ? [call, call] : []),
      ];
      const source = `${[...lines, "exit"].join("\n")}\n`;
      const levels = levelsOf(form);
      out.push({
        name: `${type}, a copy of the default, ${calls}`,
        source,
        place: "out",
        form: type,
        decision: "a copy of the default",
        levels,
        checks: [],
        runs: [],
        globals: {},
        executable: false,
        warned: [" out = hostValue"],
        boundaries: boundaryAt("out", levels, 0, siteIn(source, " out = hostValue", "hostValue")),
      });
    }
  return out;
})();
