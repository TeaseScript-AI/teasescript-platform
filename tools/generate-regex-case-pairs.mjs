// Writes src/regex-case-pairs.ts: the simple case pairs from U+0080 on, as re2js reads them through the host's
// toLowerCase and toUpperCase when it ignores case, so that the regex engine can answer them from fixed data instead.
// Run it with the Node version in package.json, whose Unicode version (process.versions.unicode) must be the one of
// re2js's own tables, and format the result:
// node tools/generate-regex-case-pairs.mjs && npx prettier --write src/regex-case-pairs.ts
import { writeFileSync } from "node:fs";

const UNICODE_VERSION = "17.0";
if (process.versions.unicode !== UNICODE_VERSION)
  throw new Error(`This Node has Unicode ${process.versions.unicode}, not ${UNICODE_VERSION}.`);

/** The one character `text` changed into, or `undefined` when it became more than one. */
function single(text) {
  const codePoint = text.codePointAt(0);
  return text.length === (codePoint > 0xffff ? 2 : 1) ? codePoint : undefined;
}

/** re2js's Codepoint.toLowerCase: the simple lower case that maps back, or the character itself. */
function lower(codePoint) {
  const lowered = single(String.fromCodePoint(codePoint).toLowerCase());
  if (lowered === undefined) return codePoint;
  return single(String.fromCodePoint(lowered).toUpperCase()) === codePoint ? lowered : codePoint;
}

// Each pair is an upper-case character and its lower case; the generator checks that they also map back up.
const pairs = [];
for (let codePoint = 0x80; codePoint <= 0x10ffff; codePoint += 1) {
  if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue;
  const lowered = lower(codePoint);
  if (lowered !== codePoint) pairs.push([codePoint, lowered - codePoint]);
}

// Runs of upper-case characters `stride` apart whose lower case is `delta` away.
const runs = [];
for (const [codePoint, delta] of pairs) {
  const last = runs.at(-1);
  const continues =
    last !== undefined &&
    last.delta === delta &&
    (last.count === 1
      ? codePoint - last.start <= 2
      : codePoint === last.start + last.count * last.stride);
  if (!continues) {
    runs.push({ start: codePoint, count: 1, stride: 1, delta });
    continue;
  }
  if (last.count === 1) last.stride = codePoint - last.start;
  last.count += 1;
}

const numbers = runs.flatMap(({ start, count, stride, delta }) => [start, count, stride, delta]);
const lines = [];
for (let index = 0; index < numbers.length; index += 12)
  lines.push(`  ${numbers.slice(index, index + 12).join(", ")},`);
writeFileSync(
  new URL("../src/regex-case-pairs.ts", import.meta.url),
  `// Generated by tools/generate-regex-case-pairs.mjs from Unicode ${UNICODE_VERSION}. Do not edit.

/**
 * The simple case pairs from U+0080 on, which RE2 folds when it ignores case: runs of \`start, count, stride, delta\`, in
 * which each of \`count\` upper-case characters from \`start\`, \`stride\` apart, has the lower case \`delta\` away. Unicode
 * ${UNICODE_VERSION}, the version of re2js's own tables.
 */
export const REGEX_CASE_PAIR_RUNS: readonly number[] = [
${lines.join("\n")}
];
`,
);
console.log(`${pairs.length} pairs in ${runs.length} runs`);
