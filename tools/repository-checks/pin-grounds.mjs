import { ts } from "ts-morph";

// The ground check of the pins `pin-suites.mjs` lists (`pin-suites.mjs --check-grounds` runs it): a pinned value that
// is new or moved needs a changed comment where its ground is written, "N units more or fewer since #…". It proves that
// every change to a declared pin's text carries its ground; it does not prove that the pin runs. Whether it runs is the
// suite's to show (a live assertion that disagrees fails in CI), and the reviewer's.
//
// It reads each changed file holding a suite's pins, at the merge-base and at the head, with the TypeScript parser that
// `ts-morph` exports (`import { ts } from "ts-morph"`, a development dependency already): no type checker, no
// evaluation. `GROUNDS` declares, for each suite, where its expected values sit: the test or top-level `const` that
// owns them (by its title or name, found once; a test taking options, which may skip it, is refused), the expressions
// inside it that hold them, and the header whose comment grounds them all. Every assertion of a declared form in its
// test (its declared actual operand, parentheses, casts and spacing aside, or an expected operand of its declared
// shape) must be the one pin: written exactly, its own statement in the test's body or in a loop's body there, after no
// `return` or `throw` of its blocks, each name its actual operand reads declared once in the test (enums and imports
// included). Any other is refused naming its line, never dropped. A reader takes only literal values in its declared
// shapes: a numeric literal, or one counter snapshot string (`"checks 142 …"`), in the declared arrays and objects,
// each object's properties plain and named once. Any other expression there (a call, a name, arithmetic, a template, a
// concatenation, a spread, a property not declared) is refused, naming the value and the fix; so is a file that does
// not parse, at the base or at the head, an owner missing or found twice, and a shape the reader does not know. Nothing
// passes by its layout: line breaks, comments and formatting do not change what is read.
//
// Each record (a row of values, f18's object with each value labelled by its field, one counter snapshot) is compared
// by its owner, its place (with the name or index that tells it from its siblings: a closure row's or a work-c case's
// name, a family's or a shape's `name`, a position elsewhere) and its values in order. A head record whose values a
// base record of the same owner and place held is unchanged, each base record matching one head record; any other head
// record is new or re-pinned and needs a touched comment: a comment on lines of its own, with an added line of the
// change among them (lines counted by `\n`, as Git counts them), either leading the record or a container of it up to
// the statement of its owner that holds it, or leading its owner's header (a test, and the test's first statement; or
// the declared anchor of a pin outside a test). It judges that the ground was touched, not whether it is true: the
// reviewer does. An owner renamed in place is refused, as its base cannot be found: rename it in a change of its own. A
// suite whose pins are listed sites (`listed`) is not read: each site's reason names it, as its own test requires. A
// value changed after its declaration, by other code, is not read: the declared literal is the pin.
//
// Its tests read the frozen suite texts of their fixture, generated by `pin-grounds.generate.mjs` (its header says from
// what), never the live suites, so a re-pin on main leaves them green. A change to this file or to its readers runs
// `node --test tools/repository-checks/pin-grounds.full.test.mjs`, every expected value moved by one, and quotes its
// result.

const COUNTERS = /^[A-Za-z]+ \d+(?: [A-Za-z]+ \d+)*$/u;
const FIX_SHAPE =
  "Write the value as a literal in its declared shape, or declare the shape in tools/repository-checks/pin-grounds.mjs.";
const FIX_FORM =
  "Keep one assertion of the declared form, written as declared where its test runs, or declare the form in tools/repository-checks/pin-grounds.mjs.";
const FIX_OWNER =
  "Restore it, or update its declaration in tools/repository-checks/pin-grounds.mjs.";

/** A file parsed as TypeScript, with its parse errors' count. */
export function parse(file, text) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  return { source, errors: source.parseDiagnostics.length };
}

/** Each source's line starts, by `\n` alone, as Git counts lines (TypeScript's own map also breaks at U+2028). */
const lineStarts = new WeakMap();

/** The 1-based line of a position, as Git numbers it. */
function lineOf(source, position) {
  let starts = lineStarts.get(source);
  if (starts === undefined) {
    starts = [0];
    for (let at = source.text.indexOf("\n"); at !== -1; at = source.text.indexOf("\n", at + 1))
      starts.push(at + 1);
    lineStarts.set(source, starts);
  }
  let [low, high] = [0, starts.length - 1];
  while (low < high) {
    const middle = Math.ceil((low + high) / 2);
    if (starts[middle] <= position) low = middle;
    else high = middle - 1;
  }
  return low + 1;
}

/** The top-level `test(…)` statements whose title starts with `title`. */
const testsTitled = (source, title) =>
  source.statements.filter((statement) => {
    const call = ts.isExpressionStatement(statement) ? statement.expression : undefined;
    return (
      call !== undefined &&
      ts.isCallExpression(call) &&
      ts.isIdentifier(call.expression) &&
      call.expression.text === "test" &&
      call.arguments.length > 0 &&
      ts.isStringLiteralLike(call.arguments[0]) &&
      call.arguments[0].text.startsWith(title)
    );
  });

/** The variable statements among `statements` declaring `name`. */
const declaring = (statements, name) =>
  statements.filter(
    (statement) =>
      ts.isVariableStatement(statement) &&
      statement.declarationList.declarations.some(
        (declaration) => ts.isIdentifier(declaration.name) && declaration.name.text === name,
      ),
  );

/** The names `node` declares below it: variables, binding patterns' names, parameters, functions and classes. */
const declarationsIn = (node, name) =>
  within(
    node,
    (child) =>
      (ts.isVariableDeclaration(child) ||
        ts.isParameter(child) ||
        ts.isBindingElement(child) ||
        ts.isFunctionDeclaration(child) ||
        ts.isClassDeclaration(child) ||
        ts.isEnumDeclaration(child) ||
        ts.isModuleDeclaration(child) ||
        ts.isImportClause(child) ||
        ts.isImportSpecifier(child) ||
        ts.isNamespaceImport(child) ||
        ts.isImportEqualsDeclaration(child)) &&
      child.name !== undefined &&
      ts.isIdentifier(child.name) &&
      child.name.text === name,
  );

/** Whether a variable statement is `const`. */
const isConst = (statement) => (statement.declarationList.flags & ts.NodeFlags.Const) !== 0;

/** The nodes below `node`, itself included, that `accept` takes, in source order. */
function within(node, accept) {
  const found = [];
  const visit = (child) => {
    if (accept(child)) found.push(child);
    ts.forEachChild(child, visit);
  };
  visit(node);
  return found;
}

/** An `assert.<method>(…)` call whose first argument `actual` accepts. */
const isAssert = (node, method, actual) =>
  ts.isCallExpression(node) &&
  ts.isPropertyAccessExpression(node.expression) &&
  node.expression.getText() === `assert.${method}` &&
  node.arguments.length >= 2 &&
  actual(node.arguments[0]);

/** A property assignment of an object literal by its name, or `undefined`. */
const propertyOf = (object, name) =>
  object.properties.find(
    (property) => ts.isPropertyAssignment(property) && property.name.getText() === name,
  );

/** A property's name as a key: an identifier's or a literal's text. */
const keyOf = (property) =>
  property.name !== undefined &&
  (ts.isIdentifier(property.name) ||
    ts.isStringLiteral(property.name) ||
    ts.isNumericLiteral(property.name))
    ? property.name.text
    : undefined;

/** What a node is, for a refusal. */
function kindOf(node) {
  if (ts.isCallExpression(node)) return `a call (${node.expression.getText()})`;
  if (ts.isIdentifier(node)) return `a name (${node.text})`;
  if (ts.isPropertyAccessExpression(node)) return `a name (${node.getText()})`;
  if (ts.isBinaryExpression(node)) return "arithmetic or a concatenation";
  if (ts.isTemplateExpression(node) || ts.isNoSubstitutionTemplateLiteral(node))
    return "a template";
  if (ts.isStringLiteral(node)) return "a string";
  if (ts.isPrefixUnaryExpression(node)) return "a signed or negated value";
  if (ts.isSpreadElement(node)) return "a spread";
  if (ts.isOmittedExpression(node)) return "an omitted element";
  return `a ${ts.SyntaxKind[node.kind]}`;
}

/**
 * One file's reading: its records, each `{ owner, place, values, node }`, and its refusals, each `{ line, what, fix }`.
 * A reader names the owner it reads in (`within`), adds records, and refuses what it cannot read.
 */
class Reading {
  constructor(source) {
    this.source = source;
    this.records = [];
    this.refusals = [];
    this.owners = [];
    this.owner = undefined;
  }
  refuse(node, what, fix = FIX_SHAPE) {
    this.refusals.push({ line: lineOf(this.source, node.getStart()), what, fix });
  }
  /** Exactly one of `nodes`; else a refusal that `what` is not found once. */
  one(nodes, what) {
    if (nodes.length === 1) return nodes[0];
    this.refusals.push({
      line: nodes.length > 1 ? lineOf(this.source, nodes[1].getStart()) : 1,
      what: `${what} is ${nodes.length === 0 ? "not found" : `found ${nodes.length} times`}`,
      fix: FIX_OWNER,
    });
    return undefined;
  }
  /** Reads in `owner` (`{ name, header, scope }`): its records are its, grounded by its header. */
  in(owner, read) {
    this.owners.push(owner);
    this.owner = owner;
    read();
    this.owner = undefined;
  }
  record(place, values, node) {
    this.records.push({ owner: this.owner, place, values, node });
  }
  /** A numeric literal's value, separators aside; else a refusal and `undefined`. */
  number(node, place) {
    if (ts.isNumericLiteral(node)) return node.getText().replaceAll("_", "");
    this.refuse(node, `${place} is ${kindOf(node)}, not a numeric literal`);
    return undefined;
  }
  /** An array literal's elements, each read by `each`; else a refusal. */
  array(node, place, each) {
    if (!ts.isArrayLiteralExpression(node)) {
      this.refuse(node, `${place} is ${kindOf(node)}, not an array literal`);
      return;
    }
    for (const element of node.elements)
      if (ts.isSpreadElement(element) || ts.isOmittedExpression(element))
        this.refuse(element, `${place} holds ${kindOf(element)}`);
      else each(element);
  }
  /** Numeric literals: their values, `undefined` once one is not. */
  numbers(node, place) {
    const values = [];
    let read = ts.isArrayLiteralExpression(node);
    this.array(node, place, (element) => {
      const value = this.number(element, place);
      if (value === undefined) read = false;
      values.push(value);
    });
    return read ? values : undefined;
  }
  /** A row of numeric literals as one record. */
  row(node, place) {
    const values = this.numbers(node, place);
    if (values !== undefined) this.record(place, values, node);
  }
  /** Rows `depth` arrays deep, each innermost row a record placed by its indices. */
  rows(node, place, depth) {
    if (depth === 0) this.row(node, place);
    else {
      let index = 0;
      this.array(node, place, (element) => this.rows(element, `${place}[${index++}]`, depth - 1));
    }
  }
  /** A counter snapshot string as one record. */
  counters(node, place) {
    if (ts.isStringLiteral(node) && COUNTERS.test(node.text))
      this.record(place, node.text.split(" "), node);
    else this.refuse(node, `${place} is ${kindOf(node)}, not one counter snapshot string`);
  }
  /**
   * An object literal whose properties are all plain and named once, `expected` naming those read (each read by its
   * function, each required) and `inputs` whether others may sit beside them unread; else a refusal and `false`.
   */
  object(node, place, expected, inputs = false) {
    if (!ts.isObjectLiteralExpression(node)) {
      this.refuse(node, `${place} is ${kindOf(node)}, not an object literal`);
      return false;
    }
    let known = true;
    const seen = new Set();
    for (const property of node.properties) {
      const key = ts.isPropertyAssignment(property) ? keyOf(property) : undefined;
      if (key === undefined || seen.has(key) || (!inputs && !Object.hasOwn(expected, key))) {
        this.refuse(
          property,
          key !== undefined && seen.has(key)
            ? `${place} names ${key} twice`
            : `${place} holds ${kindOf(property)}, not ${inputs ? "a plain property" : `one of ${Object.keys(expected).join(", ")}`}`,
        );
        known = false;
      }
      if (key !== undefined) seen.add(key);
    }
    for (const [name, each] of Object.entries(expected)) {
      const property = propertyOf(node, name);
      if (property === undefined) {
        this.refuse(node, `${place} has no ${name}`);
        known = false;
      } else if (known) each(property.initializer, `${place}.${name}`);
    }
    return known;
  }
  /** A string literal's text, for a record's identity; else a refusal and `undefined`. */
  identity(node, place) {
    if (node !== undefined && ts.isStringLiteral(node)) return node.text;
    this.refuse(
      node ?? this.source,
      `${place} is ${node === undefined ? "missing" : kindOf(node)}, not a string literal naming it`,
    );
    return undefined;
  }
  /**
   * The array literal a `const` statement of `body` declares as `name`, read element by element: `name` declared once
   * in the test, with its initializer; else a refusal.
   */
  declaredArray(body, name, what, each) {
    const statement = this.one(declaring(body.statements, name), what);
    if (statement === undefined) return;
    const declaration = statement.declarationList.declarations.find(
      (each) => each.name.getText() === name,
    );
    const declared = declarationsIn(body, name).length;
    if (!isConst(statement) || declaration.initializer === undefined || declared !== 1) {
      this.refuse(
        statement,
        declared !== 1
          ? `${name} is declared ${declared} times in the test`
          : `${name} is not a const with its table as its initializer`,
        FIX_OWNER,
      );
      return;
    }
    this.array(declaration.initializer, name, each);
  }
}

/** The block body of a test's callback, or `undefined`. */
function bodyOf(test) {
  const callback = test.expression.arguments.at(-1);
  return callback !== undefined &&
    (ts.isArrowFunction(callback) || ts.isFunctionExpression(callback)) &&
    ts.isBlock(callback.body)
    ? callback.body
    : undefined;
}

/** A reader in the test whose title starts with `title`: `read(reading, body)` in it, grounded by its header. */
const inTest = (title, read) => (reading) => {
  const test = reading.one(testsTitled(reading.source, title), `the test "${title}…"`);
  if (test === undefined) return;
  const body = bodyOf(test);
  if (body === undefined || test.expression.arguments.length !== 2) {
    reading.refuse(
      test,
      body === undefined
        ? `the test "${title}…" has no block body`
        : `the test "${title}…" takes options (it may be skipped): its pins are not read`,
      FIX_OWNER,
    );
    return;
  }
  reading.in({ name: title, header: [test, body.statements[0]].filter(Boolean), scope: body }, () =>
    read(reading, body),
  );
};

/** A reader of the top-level declaration `name`, grounded at the node `anchor` finds. */
const inDeclaration = (name, anchor, read) => (reading) => {
  const statement = reading.one(
    declaring(reading.source.statements, name),
    `the declaration of ${name}`,
  );
  const declaration = statement?.declarationList.declarations.find(
    (each) => each.name.getText() === name,
  );
  if (declaration === undefined) return;
  const declared = declarationsIn(reading.source, name).length;
  if (!isConst(statement) || declaration.initializer === undefined || declared !== 1) {
    reading.refuse(
      statement,
      declared !== 1
        ? `${name} is declared ${declared} times in the file`
        : `${name} is not a const with its table as its initializer`,
      FIX_OWNER,
    );
    return;
  }
  const header = anchor(reading);
  if (header === undefined) return;
  reading.in({ name, header: [header], scope: statement.parent }, () =>
    read(reading, declaration.initializer),
  );
};

/**
 * The one `assert.<method>(<actual>, <expected>, …)` in `body` that is its pin, its expected operand read by `read`.
 * Every assertion of the declared form in the test (`assert.<method>` whose actual operand is the declared one,
 * parentheses, casts and spacing aside, or whose expected operand takes the declared shape, `shape`) must be that one
 * pin: written exactly, its own statement where the test runs (`runsInTest`), after no `return` or `throw` of its
 * blocks, and alone; any other is refused, naming its line, never dropped.
 */
const assertion = (method, actual, describe, read, shape) => (reading, body) => {
  const calls = within(
    body,
    (node) =>
      isAssertCall(node, method) &&
      (actual(unwrapped(node.arguments[0])) || shape(unwrapped(node.arguments[1]))),
  );
  const pins = calls.filter(
    (call) => actual(call.arguments[0]) && runsInTest(call, body) && !afterExit(call, body),
  );
  for (const call of calls)
    if (call !== pins[0])
      reading.refuse(
        call,
        pins.includes(call)
          ? `a second assert.${method}(${describe}) in the test`
          : `an assert.${method}(${describe}) that is not read as the pin (in a branch, a function, a block of its own or after a return or throw, or written another way)`,
        FIX_FORM,
      );
  if (pins.length === 0 && calls.length === 0)
    reading.one(calls, `the assertion assert.${method}(${describe}, …)`);
  const call = pins[0];
  if (call === undefined || calls.length !== 1) return;
  // (a name the actual operand reads but does not declare, declared twice in the test, may bind a decoy)
  const actualOperand = call.arguments[0];
  const names = new Set(
    within(actualOperand, (node) => ts.isIdentifier(node) && !isPropertyName(node))
      .map((node) => node.text)
      .filter((name) => declarationsIn(actualOperand, name).length === 0),
  );
  const twice = [...names].filter((name) => declarationsIn(body, name).length > 1);
  if (twice.length > 0)
    reading.refuse(
      call,
      `assert.${method}(${describe})'s ${twice.join(", ")} is declared more than once in the test`,
      FIX_OWNER,
    );
  else read(call.arguments[1], `assert.${method}(${describe})`);
};

/** An `assert.<method>(…)` call with two operands at least. */
const isAssertCall = (node, method) =>
  ts.isCallExpression(node) &&
  ts.isPropertyAccessExpression(node.expression) &&
  node.expression.getText() === `assert.${method}` &&
  node.arguments.length >= 2;

/** An expression without the parentheses, non-null marks and casts around it. */
function unwrapped(node) {
  while (
    ts.isParenthesizedExpression(node) ||
    ts.isNonNullExpression(node) ||
    ts.isAsExpression(node) ||
    ts.isTypeAssertionExpression(node) ||
    ts.isSatisfiesExpression(node)
  )
    node = node.expression;
  return node;
}

/** Whether a `return` or `throw` statement comes before an assertion's statement in one of its blocks in the test. */
function afterExit(call, body) {
  for (
    let statement = call.parent;
    statement !== body && statement !== undefined;
    statement = statement.parent
  ) {
    const block = statement.parent;
    if (block === undefined || !ts.isBlock(block)) continue;
    for (const before of block.statements) {
      if (before === statement) break;
      if (ts.isReturnStatement(before) || ts.isThrowStatement(before)) return true;
    }
  }
  return false;
}

/**
 * Whether an assertion runs as the test runs: its own statement, in the test's body or in loops' bodies there, with no
 * function or bare block between.
 */
function runsInTest(call, body) {
  if (!ts.isExpressionStatement(call.parent)) return false;
  for (let node = call.parent.parent; node !== body; node = node.parent) {
    const loop = (child) =>
      ts.isForOfStatement(child) || ts.isForStatement(child) || ts.isForInStatement(child);
    if (node === undefined || !(loop(node) || (ts.isBlock(node) && loop(node.parent))))
      return false;
  }
  return true;
}

/** Whether an identifier names a property (`x.name`, `{ name: … }`) rather than a value. */
const isPropertyName = (node) =>
  (ts.isPropertyAccessExpression(node.parent) && node.parent.name === node) ||
  (ts.isPropertyAssignment(node.parent) && node.parent.name === node);

/** Whether an expression is exactly `text`, spacing aside. */
const named = (text) => (node) => node.getText().replace(/\s+/gu, "") === text.replace(/\s+/gu, "");

/** The declared shapes of an expected operand, for finding every assertion of the declared form. */
const isNumber = (node) => ts.isNumericLiteral(unwrapped(node));
const holdsNumbers = (node) =>
  ts.isArrayLiteralExpression(node) &&
  within(node, (child) => ts.isNumericLiteral(child)).length > 0;
const hasTotal = (node) =>
  ts.isObjectLiteralExpression(node) && propertyOf(node, "total") !== undefined;

